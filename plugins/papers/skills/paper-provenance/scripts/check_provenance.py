def run_text(cmd, root, env=None):
    """What a generator prints, or None and the reason it printed nothing usable."""
    try:
        p = subprocess.run(cmd, shell=True, cwd=root, capture_output=True, text=True, timeout=CMD_TIMEOUT, env=env)
    except subprocess.TimeoutExpired:
        return None, "timed out"
    if p.returncode:
        return None, f"exit code {p.returncode}: {p.stderr.strip()[-200:]}"
    if not p.stdout.strip():
        return None, "printed nothing; it must print the whole file"
    return p.stdout, ""


def check_sources(where, note, root, fail, generated):
    """A source note is one or more project paths, each optionally followed by a colon and words."""
    if WITHDRAWN in note:
        fail(f"{where}: {note} reads a withdrawn run")
        return
    for item in note.split(";"):
        path = item.split(":")[0].strip()
        full = os.path.realpath(os.path.join(root, path))
        if not os.path.isfile(full):
            fail(f"{where}: source {path} is not a file in the project")
        elif full == generated:
            fail(f"{where}: {path} is the generated file itself")
        for d in re.findall(r"results/[^/\s'\"]+", path):
            if os.path.isdir(os.path.join(root, d)) and not os.path.exists(os.path.join(root, d, "MANIFEST.txt")):
                fail(f"{where}: {d} has no MANIFEST.txt")


def traced(cmd, root, scratch):
    """Run the generator with the tracer; its output and the project files it read, or None if untraced."""
    site = os.path.join(scratch, "site")
    os.makedirs(site, exist_ok=True)
    open(os.path.join(site, "sitecustomize.py"), "w").write(TRACER)
    log = os.path.join(scratch, "trace.log")
    if os.path.exists(log):
        os.remove(log)
    env = dict(os.environ, PROVENANCE_TRACE=log, PYTHONDONTWRITEBYTECODE="1",
               PYTHONPATH=os.pathsep.join(x for x in (site, os.environ.get("PYTHONPATH")) if x))
    out, why = run_text(cmd, root, env)
    if not os.path.exists(log):
        return out, why, None, [], []
    top = os.path.realpath(root) + os.sep
    seen, outside, programs = set(), set(), []
    for line in open(log, encoding="utf-8", errors="replace"):
        line = line.rstrip("\n")
        if line.startswith("!"):
            programs.append(line[1:])
            continue
        p = os.path.realpath(line)
        if not os.path.isfile(p) or "__pycache__" in p or "site-packages" in p or p.endswith(CODE_FILES):
            if not (p.startswith(top) and p.endswith(".py") and os.path.isfile(p)):
                continue
        if p.startswith(top):
            if not p.startswith(top + "."):
                seen.add(p[len(top):])
        elif not p.startswith(SYSTEM_PLACES + (os.path.realpath(scratch), os.path.realpath(sys.prefix))) \
                and os.path.basename(p) != "pyvenv.cfg":
            outside.add(p)
    return out, why, seen, sorted(outside), programs


def altered(text):
    """Variants of a source: its decimals (or integers, if it has no decimals) each scaled differently; first and last row gone."""
    draw = random.Random(20261101)
    noise = lambda m: repr(round(float(m.group(0)) * draw.uniform(0.4, 1.6) + 0.0113, 6))
    first = re.sub(r"(?<![\w.])\d+\.\d+(?:[eE][-+]?\d+)?(?![\w.])", noise, text)
    if first == text:
        first = re.sub(r"(?<![\w.-])\d+(?![\w.-])", noise, text)
    lines = text.rstrip("\n").split("\n")
    return [first, "\n".join(lines[:-1]) + "\n", "\n".join(lines[:1] + lines[2:]) + "\n"]


def stated_numbers(text):
    """Each number the file states, in order, with whether it is in a macro definition."""
    out = []
    for line in text.split("\n"):
        code = re.sub(r"(?<!\\)%.*$", "", line)
        macro = bool(re.match(r"\s*\\(?:new|renew|provide)command|\s*\\[gex]?def", code))
        bare = re.sub(r"\\[a-zA-Z]+", lambda c: " " * len(c.group(0)), code)
        out += [(m.group(0), macro) for m in NUMBER.finditer(bare) if m.group(0)]
    return out


def in_project(cmd, root):
    top = os.path.realpath(root) + os.sep
    names = [t.strip("'\"") for t in re.split(r"[\s=<>|;]+", cmd) if t]
    return [n for n in names if os.path.isfile(os.path.join(root, n)) and os.path.realpath(os.path.join(root, n)).startswith(top)]


def respond(name, raw, cmd, root, scratch, sources, reads, fail, review):
    """Alter each declared text source in a copy and see which printed numbers move."""
    work = os.path.join(scratch, "copy")
    shutil.rmtree(work, ignore_errors=True)
    top = os.path.realpath(root) + os.sep
    for rel in set(reads) | {os.path.relpath(os.path.realpath(os.path.join(root, n)), top) for n in in_project(cmd, root)}:
        os.makedirs(os.path.dirname(os.path.join(work, rel)), exist_ok=True)
        shutil.copy2(os.path.join(root, rel), os.path.join(work, rel))
    stated = stated_numbers(raw)
    moved = [False] * len(stated)
    untested = False
    for src in sources:
        path = os.path.join(work, src)
        try:
            original = open(path, encoding="utf-8").read()
        except (OSError, UnicodeDecodeError):
            review.append(f"{name}: binary source not altered, so not tested: {src}")
            untested = True
            continue
        ran = changed = False
        for variant in altered(original):
            open(path, "w", encoding="utf-8").write(variant)
            out, _ = run_text(cmd, work)
            if out is None:
                continue
            ran = True
            if out.strip() != raw.strip():
                changed = True
                now = stated_numbers(out)
                if len(now) == len(stated):
                    moved = [a or x != y for a, x, y in zip(moved, stated, now)]
        open(path, "w", encoding="utf-8").write(original)
        if not ran:
            review.append(f"{name}: the generator stops whenever {src} is altered, so its numbers are not tested")
            untested = True
        elif not changed:
            review.append(f"{name}: no output changed when {src} was altered")
    for (token, macro), went in zip(stated, moved):
        if went:
            continue
        if untested:
            review.append(f"{name}: {token} was not shown to depend on its source")
        elif "." in token:
            fail(f"{name}: {token} does not change when its sources change, so it is not computed from them")
        elif macro:
            review.append(f"{name}: {token} did not change when its sources were altered")


def source_paths(note):
    return [item.split(":")[0].strip() for item in note.split(";") if item.split(":")[0].strip()]


def hard_coded(value, cmd, root, extra=()):
    """The generator's own files, if one holds a decimal value of three or more figures as a literal."""
    if "." not in value or len(plain(value).replace(".", "").lstrip("0")) < 3:
        return None
    want = decimal.Decimal(plain(value))
    for t in in_project(cmd, root) + list(extra):
        code = re.sub(r"#.*$", "", open(os.path.join(root, t), encoding="utf-8", errors="replace").read(), flags=re.M)
        if any(decimal.Decimal(x) == want for x in re.findall(r"(?<![\w.])\d+\.\d+(?![\w.])", code)):
            return t
    return None


def check_generated(path, raw, cmd, root, args, fail, warn, review, names):
    name = os.path.basename(path)
    if WITHDRAWN in cmd:
        fail(f"{name}: its command {cmd} reads a withdrawn run")
        return
    if not names_a_file(cmd, root):
        fail(f"{name}: its command names no project file: {cmd}")
    if any(os.path.realpath(os.path.join(root, t.strip("'\""))) == os.path.realpath(path) for t in re.split(r"[\s=<>|;]+", cmd) if t):
        fail(f"{name}: its command reads the generated file itself: {cmd}")
    macros = list(GENERATED_MACRO.finditer(raw))
    names.update(m.group(1) for m in macros)
    whole = [m.group(1) for m in SOURCE_NOTE.finditer(raw) if not raw[raw.rfind("\n", 0, m.start()) + 1:m.start()].strip()]
    me = os.path.realpath(path)
    for note in whole:
        check_sources(name, note, root, fail, me)
    for m in macros:
        macro, value, note = m.groups()
        if note:
            check_sources(f"{name}: {macro}", note, root, fail, me)
        elif not whole:
            fail(f"{name}: {macro} has no source note")
    if not macros and not whole:
        fail(f"{name}: it has no source note")
    whole_paths = [s for note in whole for s in source_paths(note)]
    sources = list(dict.fromkeys(whole_paths + [s for m in macros if m.group(3) for s in source_paths(m.group(3))]))
    for s in sources:
        if not s.startswith(("results/", "data/")):
            review.append(f"{name}: source outside results/ and data/: {s}")
    body = re.sub(r"\\[a-zA-Z]+", lambda c: " " * len(c.group(0)), blank_re(raw, r"(?<!\\)%.*$", re.M))
    if args.no_run:
        warn(f"{name}: not rerun, because of --no-run")
        reads = ()
    else:
        with tempfile.TemporaryDirectory() as scratch:
            out, why, reads, outside, programs = traced(cmd, root, scratch)
            if out is None:
                fail(f"{name}: its command failed: {why}")
                return
            if out.strip() != raw.strip():
                fail(f"{name}: differs from what {cmd} prints now, so it is stale or was edited by hand")
            if reads is None:
                shown = ", ".join(t for t, _ in stated_numbers(raw)[:30])
                review.append(f"{name}: generator not traced, so its reads and sources are untested: {cmd}: {shown}")
                reads = ()
            else:
                code = [r for r in reads if r.endswith(".py")]
                data = [r for r in reads if not r.endswith(".py") and os.path.basename(r) != "MANIFEST.txt"]
                for r in data:
                    if WITHDRAWN in r:
                        fail(f"{name}: the generator read {r}, a withdrawn run")
                    elif r not in sources:
                        fail(f"{name}: the generator read {r}, which is not a declared source")
                for s in sources:
                    if s not in data and os.path.isfile(os.path.join(root, s)):
                        fail(f"{name}: declared source {s} is never read by the generator")
                for x in outside:
                    review.append(f"{name}: the generator read a file outside the project: {x}")
                for x in sorted(set(programs)):
                    review.append(f"{name}: the generator ran another program, whose reads are not traced: {x}")
                respond(name, raw, cmd, root, scratch, [s for s in sources if s in data], reads, fail, review)
    extra = [r for r in reads if r.endswith(".py")]
    for token in dict.fromkeys(m.group(0) for m in NUMBER.finditer(body) if m.group(0)):
        where = hard_coded(token, cmd, root, extra)
        if where:
            fail(f"{name}: {token} is written into {where}, not computed")


def check_row(n, r, root, keys, args, fail, cited, manuscripts):
    text, value, kind, source = ((r.get(k) or "").strip() for k in ("text", "value", "kind", "source"))
    if kind not in KINDS:
        fail(f"row {n}: unknown kind {kind!r}")
        return
    if not text or not source:
        fail(f"row {n}: text and source are both required")
        return
    if value == "*" and len(text) > 400:
        fail(f"row {n}: a * row quotes one sentence or a table's caption, not {len(text)} characters")
    if value and value != "*" and plain(value) not in numbers_in(text):
        fail(f"row {n}: value {value} is not in its text: {text}")
    if kind in ("calculation", "file") and WITHDRAWN in source:
        fail(f"row {n}: {source} reads a withdrawn run")
        return
    if kind == "exempt" and len(source.split()) < 2:
        fail(f"row {n}: an exempt row needs a reason in words")
    if 0 < len((r.get("typed") or "").split()) < 2:
        fail(f"row {n}: a typed number needs a reason in words")
    if kind == "exempt" and (r.get("typed") or "").strip():
        fail(f"row {n}: an exempt row takes no typed reason; a value the code does not reproduce stays a failure")
    if kind == "calculation":
        if not value:
            fail(f"row {n}: a calculation needs a value")
            return
        for d in re.findall(r"results/[^/\s'\"]+", source):
            if os.path.isdir(os.path.join(root, d)) and not os.path.exists(os.path.join(root, d, "MANIFEST.txt")):
                fail(f"row {n}: {d} has no MANIFEST.txt")
        if args.no_run:
            return
        got, out = run(source, root)
        if got is None:
            fail(f"row {n}: calculation for {value}: {out}")
            return
        if not names_a_file(source, root):
            fail(f"row {n}: the calculation names no project file: {source}")
        if value == "*":
            r["_body"] = out
            return
        want = number_of(value)
        step = decimal.Decimal(1).scaleb(want.as_tuple().exponent) / 2
        if abs(got - want) > step:
            fail(f"row {n}: printed {value}, calculation gives {got}: {text}")
    elif kind == "file":
        path = source.split(":")[0]
        p = os.path.realpath(os.path.join(root, path))
        if p in manuscripts:
            fail(f"row {n}: {path} is the manuscript itself")
            return
        try:
            body = open(p, encoding="utf-8", errors="replace").read()
        except OSError:
            fail(f"row {n}: cannot read {source}")
            return
        if value == "*":
            r["_body"] = body
        elif value and not in_source(plain(value), body):
            fail(f"row {n}: {value} is not in {source}")
    elif kind == "citation":
        key = source.split(":")[0].strip()
        if keys is None:
            fail(f"row {n}: a citation row needs --bib")
        elif key not in keys:
            fail(f"row {n}: citation key {key} is not in the bibliography")
        elif key not in cited:
            fail(f"row {n}: the manuscript never cites {key}")


INPUTS = re.compile(r"\\(?:input|include|subfile|InputIfFileExists|@input|verbatiminput)\s*\{([^}]*)\}|\\input\s+([\w./-]+)|\\(?:sub)?import\*?\s*\{([^}]*)\}\s*\{([^}]*)\}")


def with_inputs(paths, fail, review):
    """The manuscripts and the text files they bring in."""
    out, todo = [], list(paths)
    while todo:
        p = todo.pop(0)
        if os.path.realpath(p) in [os.path.realpath(q) for q in out]:
            continue
        if p in paths and not p.endswith((".tex", ".md")):
            sys.exit(f"a manuscript must be .tex or .md: {p}")
        try:
            raw = open(p, encoding="utf-8", errors="replace").read()
        except OSError as e:
            sys.exit(f"cannot read the manuscript: {e}")
        out.append(p)
        if p.endswith(".md"):
            continue
        here = os.path.dirname(p)
        code = re.sub(r"(?<!\\)%.*$", "", raw, flags=re.M)
        for m in INPUTS.finditer(code):
            name = m.group(1) or m.group(2) or ((m.group(3) or "") + (m.group(4) or ""))
            if "\\" in name or "#" in name:
                fail(f"{os.path.basename(p)}: cannot follow {m.group(0)}; name the file directly")
                continue
            q = next((os.path.join(here, c) for c in (name, name + ".tex") if os.path.isfile(os.path.join(here, c))), None)
            if q and q.endswith((".pgf", ".tikz", ".pdf_tex")):
                review.append(f"{os.path.basename(p)}: not scanned: {name}")
            elif q:
                todo.append(q)
        for m in re.finditer(r"\\(usepackage|documentclass|RequirePackage)(?:\[[^\]]*\])?\{([^}]*)\}", code):
            for name in m.group(2).split(","):
                ext = ".cls" if m.group(1) == "documentclass" else ".sty"
                if os.path.isfile(os.path.join(here, name.strip() + ext)):
                    review.append(f"{os.path.basename(p)}: local file not scanned: {name.strip() + ext}")
        shown = [n for b in re.findall(r"\\begin\{(?:equation|align|gather|multline|eqnarray|displaymath)\*?\}(.*?)\\end\{", code, re.S) + re.findall(r"\\\[(.*?)\\\]", code, re.S)
                 for n in re.findall(r"(?<![\w.])\d+\.\d+", b)]
        if shown:
            review.append(f"{os.path.basename(p)}: decimals in display equations are not checked: {', '.join(shown[:30])}")
    return out


def table_around(path, raw, a, b):
    """The table that holds this span, or the span itself."""
    if path.endswith(".tex"):
        for m in TABLE_ENV.finditer(raw):
            if m.start() <= a and b <= m.end():
                return m.span()
        return a, b
    start = raw.rfind("\n", 0, a) + 1
    end = raw.find("\n", b)
    end = len(raw) if end < 0 else end
    if not raw[start:end].lstrip().startswith("|"):
        return a, b
    while start > 0:
        prev = raw.rfind("\n", 0, start - 1) + 1
        if not raw[prev:start].lstrip().startswith("|"):
            break
        start = prev
    while end < len(raw):
        nxt = raw.find("\n", end + 1)
        nxt = len(raw) if nxt < 0 else nxt
        if not raw[end + 1:nxt].lstrip().startswith("|"):
            break
        end = nxt
    return start, end


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("manuscripts", nargs="+")
    ap.add_argument("--ledger", required=True)
    ap.add_argument("--root", default=".")
    ap.add_argument("--bib", nargs="*", default=None)
    ap.add_argument("--no-run", action="store_true", help="check records without running their commands")
    ap.add_argument("--sentences", action="store_true", help="list sentences with no citation and no record, for review")
    ap.add_argument("--ack", action="store_true", help="for a person, in a terminal: acknowledge the review list")
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    problems, warnings, review = [], [], []
    try:
        rows = list(csv.DictReader(open(args.ledger, encoding="utf-8", newline=""), delimiter="\t", quoting=csv.QUOTE_NONE))
    except OSError as e:
        sys.exit(f"cannot read the ledger: {e}")
    if rows and not {"text", "value", "kind", "source"} <= set(rows[0]):
        sys.exit("the ledger's header must be: text value kind source")
    keys = tex_keys(args.bib) if args.bib else None
    args.manuscripts = with_inputs(args.manuscripts, problems.append, review)
    written = []
    generated = set()
    names = set()
    for p in args.manuscripts:
        raw = open(p, encoding="utf-8", errors="replace").read()
        g = GENERATED.match(raw) if not p.endswith(".md") else None
        if g:
            generated.add(p)
            check_generated(p, raw, g.group(1), root, args, problems.append, warnings.append, review, names)
        else:
            written.append(p)
    for p in written:
        code = re.sub(r"(?<!\\)%.*$", "", open(p, encoding="utf-8", errors="replace").read(), flags=re.M)
        for macro in sorted(names):
            if re.search(r"\\(?:[gex]?def|let|(?:re|new|provide)command\*?|DeclareRobustCommand\*?)\s*\{?" + re.escape(macro) + r"(?![A-Za-z])", code):
                problems.append(f"{os.path.basename(p)}: redefines the generated number {macro}")
    cited = " ".join(open(p, encoding="utf-8", errors="replace").read() for p in args.manuscripts)
    manuscripts = {os.path.realpath(p) for p in args.manuscripts}
    for n, r in enumerate(rows, 2):
        check_row(n, r, root, keys, args, problems.append, cited, manuscripts)

    docs = []
    for path in written:
        raw = open(path, encoding="utf-8", errors="replace").read()
        visible = mask(path, raw)
        docs.append((path, raw, visible, *flatten(raw)))
    placed = [False] * len(rows)
    typed_here = set()
    for path, raw, visible, flat, where in docs:
        covered = []
        for i, r in enumerate(rows):
            snippet = " ".join((r.get("text") or "").split())
            if not snippet:
                continue
            value = (r.get("value") or "").strip()
            for m in re.finditer(re.escape(snippet), flat):
                placed[i] = True
                if not path.endswith(".md") and r.get("kind", "").strip() in ("calculation", "file") and not (r.get("typed") or "").strip():
                    typed_here.add(i)
                a, b = where[m.start()], where[m.end() - 1] + 1
                if value == "*":
                    a, b = table_around(path, raw, a, b)
                covered.append((a, b, "*" if value == "*" else plain(value) if value else "", i))
        tagged = [(a, b) for a, b, v, i in covered]
        for m in NUMBER.finditer(visible):
            if DIMENSION.match(m.group(0)):
                continue
            token = plain(m.group(0))
            rows_here = [i for a, b, v, i in covered if a <= m.start() and m.end() <= b and v in (token, "*")]
            ok = bool(rows_here)
            for i in rows_here:
                if (rows[i].get("value") or "").strip() == "*":
                    rows[i].setdefault("_cells", []).append(token)
                body = rows[i].get("_body")
                if body is not None and not in_source(token, body):
                    line = raw.count("\n", 0, m.start()) + 1
                    problems.append(f"{os.path.basename(path)}:{line}: {m.group(0)} is not in the source of row {i + 2}")
            if not ok:
                line = raw.count("\n", 0, m.start()) + 1
                ctx = " ".join(raw[max(0, m.start() - 40):m.end() + 30].split())
                problems.append(f"{os.path.basename(path)}:{line}: no record for {m.group(0)} in: ...{ctx}...")
        for m in NUMBER_WORD.finditer(visible):
            if not any(a <= m.start() and m.end() <= b for a, b in tagged):
                line = raw.count("\n", 0, m.start()) + 1
                warnings.append(f"{os.path.basename(path)}:{line}: number word '{m.group(0)}' has no record")
        if args.sentences:
            for s in re.finditer(r"[A-Z][^.!?\n]*(?:\n[^.!?\n]+)*[.!?]", visible):
                has_cite = re.search(r"\\\w*cite|\[@", raw[s.start():s.end()])
                if len(s.group(0).split()) >= 5 and not has_cite and not any(a < s.end() and b > s.start() for a, b in tagged):
                    line = raw.count("\n", 0, s.start()) + 1
                    print(f"unrecorded sentence {os.path.basename(path)}:{line}: {' '.join(s.group(0).split())[:120]}")
    for i in sorted(typed_here):
        problems.append(f"row {i + 2}: a computed number typed into a .tex manuscript; generate it, or give the reason in the typed column: {rows[i]['text'].strip()}")
    for i, r in enumerate(rows):
        if not placed[i] and (r.get("text") or "").strip():
            problems.append(f"row {i + 2}: its text is no longer in the manuscript: {r['text'].strip()}")

    for r in rows:
        text, value, kind, source, why = ((r.get(k) or "").strip() for k in ("text", "value", "kind", "source", "typed"))
        if kind == "exempt":
            flag = " [looks like a result]" if "." in value or "%" in value else ""
            review.append(f"exempt{flag}: {value} in \"{text}\": {source}")
        if why:
            review.append(f"typed: {value} in \"{text}\": {why}")
        if kind == "citation" and value:
            cells = ", ".join(dict.fromkeys(r.get("_cells", []))) if value == "*" else value
            review.append(f"quoted from a citation: {cells} in \"{text}\": {source}")
    review = sorted(set(review))
    stamp = hashlib.sha256("\n".join(review).encode()).hexdigest()
    ack_file = args.ledger + ".reviewed"
    try:
        done = open(ack_file).read().strip() == stamp
    except OSError:
        done = False

    for w in warnings:
        print("warning:", w)
    for p in problems:
        print("FAIL:", p)
    print(f"{len(rows)} records, {len(problems)} failures, {len(warnings)} warnings")
    if problems:
        return 1
    if review and not done:
        print("For a person to read:")
        for x in review:
            print("  " + x)
        if not args.ack:
            print(f"{len(review)} entries await a person. Everything else holds. They run this with --ack in a terminal.")
            return 3
        if not (sys.stdin.isatty() and sys.stdout.isatty()):
            print("FAIL: --ack is for a person at a terminal")
            return 1
        if input("Have you read these, and do they all hold? Type yes: ").strip() != "yes":
            return 3
        open(ack_file, "w").write(stamp + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
